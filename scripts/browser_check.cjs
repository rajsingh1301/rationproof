/* Run with the server on :8765 and Playwright available. No external websites. */
const { chromium } = require(process.env.RATIONPROOF_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
(async () => {
  fs.mkdirSync(path.join(root, 'artifacts'), {recursive:true});
  const browser = await chromium.launch({headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[]; page.on('pageerror', e=>errors.push(String(e)));
    await page.goto('http://127.0.0.1:8765');
    await page.getByText('Local image reader installed', {exact:true}).waitFor();
    await page.screenshot({path:path.join(root,'artifacts','desktop.png'),fullPage:true});
    await page.locator('[data-demo="difference"]').click();
    await page.getByText('A difference needs checking',{exact:true}).waitFor();
    assert.match(await page.locator('#report').innerText(),/SYNTHETIC DEMO/);
    const downloadEvent = page.waitForEvent('download');
    await page.locator('#export-json').click();
    const download = await downloadEvent;
    const report = JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(Number(report.report.rows[0].difference_kg),5);
    await page.locator('[data-demo="partial"]').click();
    await page.getByText('You have a balance to check',{exact:true}).waitFor();
    assert.match(await page.locator('#report').innerText(),/10 kg balance/);
    await page.locator('[data-demo="missing"]').click();
    await page.getByText('More details needed',{exact:true}).waitFor();
    await page.locator('#start-fresh').click();
    await page.locator('#file').setInputFiles(path.join(root,'static','demo-receipt.png'));
    await page.locator('#rid-0').waitFor();
    assert.equal(await page.locator('#rid-0').inputValue(),'DEMO-001');
    assert.equal(await page.locator('#issued-0-0').inputValue(),'25');
    assert.equal(await page.locator('#received-0-0').inputValue(),'');
    assert.equal(await page.locator('[data-field="confirmed"]').isChecked(),false);
    await page.locator('#month').fill('2026-11');
    await page.locator('#rice').fill('25');
    await page.locator('#received-0-0').fill('20');
    await page.locator('[data-field="confirmed"]').check();
    await page.locator('#month-complete').check();
    await page.locator('#compare').click();
    await page.getByText('A difference needs checking',{exact:true}).waitFor();
    await page.screenshot({path:path.join(root,'artifacts','comparison.png'),fullPage:true});
    await page.locator('#received-0-0').fill('25');
    assert.equal(await page.locator('[data-field="confirmed"]').isChecked(),false);
    assert.equal(await page.locator('.report-actions').isVisible(),false);
    await page.locator('[data-field="confirmed"]').check();
    await page.locator('#compare').click();
    await page.getByText('Your reviewed records agree',{exact:true}).waitFor();
    await page.locator('#file').setInputFiles(path.join(root,'static','demo-receipt.png'));
    await page.getByText('This exact receipt is already in your record. It has not been added twice.',{exact:true}).waitFor();
    assert.equal(await page.locator('.receipt-card').count(),1);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(root,'artifacts','mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'mobile overflow');
    await page.reload();
    assert.equal(await page.locator('.receipt-card').count(),0,'private records retained on reload');
    assert.deepEqual(errors,[],'browser errors');
    console.log('Browser checks passed: demos, image OCR, human review, recomputation, duplicate upload, export, mobile layout, reload clearing.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
